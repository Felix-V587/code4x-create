#!/usr/bin/env bash
#
# vp-harness setup: create a scratch Vite+ monorepo that registers a local
# `code4x` template whose bin is a shim onto this repo's built package CLI
# (`packages/create-code4x/dist/cli.mjs`).
#
# Usage: bash fixtures/vp-harness/setup.sh [TARGET_DIR]
#        (default TARGET_DIR: /tmp/opencode/vp-harness)
set -euo pipefail

TARGET="${1:-/tmp/opencode/vp-harness}"
SCRIPT_DIR="$(cd "$(dirname "${BASH_SOURCE[0]}")" && pwd)"
REPO_ROOT="$(cd "$SCRIPT_DIR/../.." && pwd)"
CLI_ABS="$REPO_ROOT/packages/create-code4x/dist/cli.mjs"

echo "== vp-harness setup =="
echo "  repo:   $REPO_ROOT"
echo "  target: $TARGET"

# Ensure the repo CLI is built (the shim imports it by absolute path).
( cd "$REPO_ROOT/packages/create-code4x" && vp pack >/dev/null )
if [ ! -f "$CLI_ABS" ]; then
  echo "error: missing built CLI at $CLI_ABS" >&2
  exit 1
fi

rm -rf "$TARGET"
mkdir -p "$TARGET/pkgs/create-code4x"

cat > "$TARGET/pnpm-workspace.yaml" <<'YAML'
packages:
  - apps/*
YAML

cat > "$TARGET/package.json" <<'JSON'
{
  "name": "vp-harness",
  "version": "0.0.0",
  "private": true,
  "type": "module",
  "devDependencies": {
    "vite-plus": "1.1.0"
  }
}
JSON

cat > "$TARGET/vite.config.ts" <<'TS'
import { defineConfig } from "vite-plus";

export default defineConfig({
  create: {
    templates: [
      {
        name: "code4x",
        description: "code4x-create harness",
        template: "./pkgs/create-code4x",
      },
    ],
  },
});
TS

cat > "$TARGET/pkgs/create-code4x/package.json" <<'JSON'
{
  "name": "create-code4x-harness",
  "version": "0.0.0",
  "private": true,
  "type": "module",
  "bin": {
    "create-code4x": "./index.mjs"
  }
}
JSON

# The shim MUST import `run` explicitly: the repo CLI's `isMain()` guard means an
# import side-effect would not execute it.
cat > "$TARGET/pkgs/create-code4x/index.mjs" <<EOF
#!/usr/bin/env node
// Generated by fixtures/vp-harness/setup.sh — do not edit by hand.
import { run } from "${CLI_ABS}";

const code = await run(process.argv.slice(2));
process.exit(code);
EOF
chmod +x "$TARGET/pkgs/create-code4x/index.mjs"

echo "== installing harness workspace root =="
( cd "$TARGET" && pnpm install ) || echo "warn: root pnpm install failed (continuing)"
echo "setup done: $TARGET"
